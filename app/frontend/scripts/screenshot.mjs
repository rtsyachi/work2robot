async function waitForServer() {
  for (let i = 0; i < 60; i++) {
    try {
      const r = await fetch(new URL('api/health', url))
      if (r.ok) return
    } catch {}
    await new Promise((r) => setTimeout(r, 1000))
  }
  throw new Error(`アプリに接続できません: ${url}`)
}

